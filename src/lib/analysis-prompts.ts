function findingVocabulary(): string {
  return FINDING_TYPES.map(t => {
    const d = FINDINGS[t]
    return `  "${t}" — ${d.label}. В лентата изглежда като: ${d.appearanceUnwrapped}. Допустими пръстени: R${d.validRings[0]}–R${d.validRings[1]}.`
  }).join('\n')
}

function priorityZoneBlock(side: Side): string {
  return PRIORITY_ZONES.map(z => {
    const secs = z.minutes[side]
      .map(([a, b]) => {
        const s1 = Math.floor(a / 5) + 1
        const s2 = Math.ceil(b / 5)
        return s1 === 1 && s2 === 12 ? 'всички сектори' : `S${s1}–S${s2}`
      })
      .join(', ')
    return `  • ${z.label}: ${secs}, редове R${z.rings[0]}–R${z.rings[1]} — ${z.description}`
  }).join('\n')
}

function ringBandBlock(): string {
  return RING_BANDS.map(
    b =>
      `  R${b.rings[0]}${b.rings[0] === b.rings[1] ? '' : `–R${b.rings[1]}`} = ${b.key} (${b.label})`
  ).join('\n')
}

export interface DetectionPromptContext {
  side: Side
  /** Кой слой е подаден като изображение. */
  layer: 'base' | 'structure' | 'pigment'
  /** Клетки, които са нечетими и трябва да бъдат пропуснати. */
  unreadableCells: Array<{ sector: number; ring: number }>
  /** Клетки с частично маскирана площ — там прагът за докладване е по-висок. */
  partialCells?: Array<{ sector: number; ring: number; readable: number }>
  /**
   * Ако лентата показва само част от пръстените (увеличен прочит), тук са
   * границите. Моделът трябва да знае, че извън тях просто няма какво да гледа.
   */
  ringRange?: [number, number]
  /** 0..100 — качество на оригиналната снимка. */
  qualityScore: number
  /**
   * Снимано ли е със светкавица. Не се предполага — извежда се от дела
   * спекуларна площ В ЗЕНИЦАТА (`metrics.pupilSpecular`).
   */
  flash?: boolean
}

